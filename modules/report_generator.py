"""
report_generator.py

Generates the downloadable Executive Report (Markdown/plain text).
Uses AI for wording/narrative when available, but always falls back to a
purely deterministic report built from calculated KPIs if AI is unavailable
— the report feature must never depend entirely on the AI service.
"""

from __future__ import annotations

from datetime import datetime
from typing import List, Optional

import pandas as pd

from modules.analytics import MetricColumns, calculate_kpis
from modules.ai_service import AIService, AIResponse, get_ai_service
from utils.helpers import format_number, format_percentage


def _fallback_report(df: pd.DataFrame, file_name: str, metric_columns: MetricColumns) -> str:
    """A fully deterministic report with no AI narrative, used when AI is unavailable."""
    kpis = calculate_kpis(df, metric_columns)
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M")

    lines = [
        "# BUSINESS PERFORMANCE REPORT",
        "",
        f"*Generated by InsightAI on {generated_at}*",
        f"*Source dataset: {file_name} ({len(df)} rows, {len(df.columns)} columns)*",
        "",
        "## Executive Summary",
        "",
        "This report summarizes the calculated key metrics for the uploaded dataset. "
        "AI-generated narrative was not available for this report — all figures below "
        "were computed directly from the data.",
        "",
        "## Key Metrics",
        "",
    ]

    for kpi in kpis:
        if kpi.value is None:
            continue
        if kpi.is_percentage:
            lines.append(f"- **{kpi.label}:** {format_percentage(kpi.value)}")
        else:
            lines.append(f"- **{kpi.label}:** {format_number(kpi.value, decimals=2)}")

    lines += [
        "",
        "## Notes",
        "",
        "- Enable AI features (add a valid GEMINI_API_KEY to your .env file) to include "
        "narrative findings, risks, and recommendations in this report.",
    ]

    return "\n".join(lines)


def generate_executive_report(
    df: pd.DataFrame,
    file_name: str,
    metric_columns: MetricColumns,
    dataset_context: str,
    insights_text: Optional[str],
    recommendations_text: Optional[str],
    ai_service: Optional[AIService] = None,
) -> str:
    """
    Build the final executive report. If insights/recommendations text is
    already available (generated earlier in the session), reuse it instead
    of making another AI call. If AI is unavailable entirely, fall back to
    a deterministic report.
    """
    service = ai_service or get_ai_service()
    generated_at = datetime.now().strftime("%Y-%m-%d %H:%M")
    kpis = calculate_kpis(df, metric_columns)

    kpi_lines = []
    for kpi in kpis:
        if kpi.value is None:
            continue
        if kpi.is_percentage:
            kpi_lines.append(f"- **{kpi.label}:** {format_percentage(kpi.value)}")
        else:
            kpi_lines.append(f"- **{kpi.label}:** {format_number(kpi.value, decimals=2)}")
    kpi_block = "\n".join(kpi_lines) if kpi_lines else "- No standard business metrics could be calculated from this dataset."

    if not service.is_available:
        return _fallback_report(df, file_name, metric_columns)

    # Ask the AI only to write the narrative summary/findings/risks/conclusion,
    # NOT to recalculate any numbers. We supply the exact KPI text so it can
    # reference it directly.
    prompt = f"""Here is the structured summary of a business dataset:

{dataset_context}

Here are the already-calculated key metrics (do not recalculate, just reference them):
{kpi_block}

Here are previously generated AI insights (may be empty):
{insights_text or "(not generated)"}

Here are previously generated AI recommendations (may be empty):
{recommendations_text or "(not generated)"}

Task: Write a professional executive business report using this exact structure with
these exact section headers:

## Executive Summary
(2-4 sentences overview)

## Key Findings
(3-5 bullet points, grounded only in the context above)

## Positive Trends
(bullet points; if none are supported by the data, write "No clear positive trends were identified in this dataset.")

## Risks
(bullet points; if none are supported by the data, write "No significant risks were identified in this dataset.")

## Recommendations
(3-5 bullet points; reuse the recommendations provided above if present)

## Conclusion
(2-3 sentences)

Do not invent numbers, causes, or facts not present above. Do not include the raw
key metrics list in your output — the application will add that separately."""

    response = service.generate(prompt, max_output_tokens=2048)

    if not response.success:
        return _fallback_report(df, file_name, metric_columns)

    report = "\n".join([
        "# BUSINESS PERFORMANCE REPORT",
        "",
        f"*Generated by InsightAI on {generated_at}*",
        f"*Source dataset: {file_name} ({len(df)} rows, {len(df.columns)} columns)*",
        "",
        "## Key Metrics",
        "",
        kpi_block,
        "",
        response.text,
    ])
    return report
